package org.scharp.sas7bdat;

/**
 * A class for generating the sequence numbers that appear on each page of a SAS7BDAT file.
 */
class PageSequenceGenerator {

    // The page sequence numbers are incremented in four-bit (nibble) ranges.
    // The lowest nibble is incremented by a nonlinear function that depends on the initial value of that nibble.
    // Once the nibble has been incremented 16 times, the overflow is carried over to an increment on the
    // next higher nibble.
    // Examples:
    //
    // For 0x63 is incremented as:
    // 0x63,0x62,0x61,0x60, 0x67,0x66,0x65,0x64, 0x6B,0x6A,0x69,0x68, 0x6F,0x6E,0x6D,0x6C,
    // 0x73,0x72,0x71,0x70, 0x77,0x76,0x75,0x74, 0x7B,0x7A,0x79,0x78, 0x7F,0x7E,0x7D,076C,
    // 0x43,0x42,0x41,0x40, 0x47,0x46,0x45,0x44, ...
    //
    private static final byte[][] sequenceFunctionByInitialValue = {
        { 0x0, 0x1, 0x2, 0x3, 0x4, 0x5, 0x6, 0x7, 0x8, 0x9, 0xA, 0xB, 0xC, 0xD, 0xE, 0xF },
        { 0x1, 0x0, 0x3, 0x2, 0x5, 0x4, 0x7, 0x6, 0x9, 0x8, 0xB, 0xA, 0xD, 0xC, 0xF, 0xE },
        { 0x2, 0x3, 0x0, 0x1, 0x6, 0x7, 0x4, 0x5, 0xA, 0xB, 0x8, 0x9, 0xE, 0xF, 0xC, 0xD },
        { 0x3, 0x2, 0x1, 0x0, 0x7, 0x6, 0x5, 0x4, 0xA, 0xB, 0x9, 0x8, 0xF, 0xE, 0xD, 0xC },
        { 0x4, 0x5, 0x6, 0x7, 0x0, 0x1, 0x2, 0x3, 0xC, 0xD, 0xE, 0xF, 0x8, 0x9, 0xA, 0xB },
        { 0x5, 0x4, 0x7, 0x6, 0x1, 0x0, 0x3, 0x2, 0xD, 0xC, 0xF, 0xE, 0x9, 0x8, 0xB, 0xA },
        { 0x6, 0x7, 0x4, 0x5, 0x2, 0x3, 0x0, 0x1, 0xE, 0xF, 0xC, 0xD, 0xA, 0xB, 0x8, 0x9 },
        { 0x7, 0x6, 0x5, 0x4, 0x3, 0x2, 0x1, 0x0, 0xF, 0xE, 0xD, 0xC, 0xB, 0xA, 0x9, 0x8 },
        { 0x8, 0x9, 0xA, 0xB, 0xC, 0xD, 0xE, 0xF, 0x0, 0x1, 0x2, 0x3, 0x4, 0x5, 0x6, 0x7 },
        { 0x9, 0x8, 0xB, 0xA, 0xD, 0xC, 0xF, 0xE, 0x1, 0x0, 0x3, 0x2, 0x5, 0x4, 0x7, 0x6 },
        { 0xA, 0xB, 0x8, 0x9, 0xE, 0xF, 0xC, 0xD, 0x2, 0x3, 0x0, 0x1, 0x6, 0x7, 0x4, 0x5 },
        { 0xB, 0xA, 0x9, 0x8, 0xF, 0xE, 0xD, 0xC, 0x3, 0x2, 0x1, 0x0, 0x7, 0x6, 0x5, 0x4 },
        { 0xC, 0xD, 0xE, 0xF, 0x8, 0x9, 0xA, 0xB, 0x4, 0x5, 0x6, 0x7, 0x0, 0x1, 0x2, 0x3 },
        { 0xD, 0xC, 0xF, 0xE, 0x9, 0x8, 0xB, 0xA, 0x5, 0x4, 0x7, 0x6, 0x1, 0x0, 0x3, 0x2 },
        { 0xE, 0xF, 0xC, 0xD, 0xA, 0xB, 0x8, 0x9, 0x6, 0x7, 0x4, 0x5, 0x2, 0x3, 0x0, 0x1 },
        { 0xF, 0xE, 0xD, 0xC, 0xB, 0xA, 0x9, 0x8, 0x7, 0x6, 0x5, 0x4, 0x3, 0x2, 0x1, 0x0 },
    };

    long initialValue;
    int pageSequenceIndex;

    /**
     * Create a new page sequence generator that starts at a given value.
     *
     * @param initialValue
     *     the initial value in the sequence.
     */
    PageSequenceGenerator(long initialValue) {
        this.initialValue = initialValue;
        pageSequenceIndex = 0;
    }

    /** Create a new page sequence generator that can be used to create legal page sequence */
    PageSequenceGenerator() {
        this(0xF4_A4_FF_F6L); // for compatibility with v0.9 of this library
    }

    /**
     * @return the first number in this page sequence.
     */
    long initialPageSequence() {
        return initialValue;
    }

    /**
     * Gets the value of a given nibble within the current sequence number.
     *
     * @param nibble
     *     The index of the nibble to get.  0 gets the least significant nibble.  1 gets the nibble at bits 4-7.
     *
     * @return The value of the requested nibble within the current sequence number.
     */
    private long getNibbleInSequence(int nibble) {
        assert 0 <= nibble;
        assert nibble < 8;

        // The sequence function depends on the initial value of the corresponding nibble.
        final int leastSignificantBit = 4 * nibble;
        byte[] sequenceFunction = sequenceFunctionByInitialValue[(int) ((initialValue >>> leastSignificantBit) & 0xF)];
        return sequenceFunction[(pageSequenceIndex >>> leastSignificantBit) & 0xF];
    }

    /**
     * @return the current number in this page sequence.
     */
    long currentPageSequence() {
        return (getNibbleInSequence(7) << 28) | // bits 28-32
            (getNibbleInSequence(6) << 24) | // bits 24-27
            (getNibbleInSequence(5) << 20) | // bits 20-23
            (getNibbleInSequence(4) << 16) | // bits 16-19
            (getNibbleInSequence(3) << 12) | // bits 12-15
            (getNibbleInSequence(2) << 8) | // bits 8-11
            (getNibbleInSequence(1) << 4) | // bits 4-7
            (getNibbleInSequence(0)); // bits 0-3
    }

    /**
     * Increments this the current number of this sequence to the next number in the sequence.
     *
     * @throws IllegalStateException
     *     if the page sequence has been exhausted.
     */
    void incrementPageSequence() {
        pageSequenceIndex++;

        // The logic in this class probably *does* support more than 0x7FFF pages, but there's no
        // way to know that SAS doesn't have alternate logic for incrementing the upper 16 bits.
        if (pageSequenceIndex > 0x7FFF) {
            throw new IllegalStateException("This code does not support more than " + 0x7FFF + " pages");
        }
    }
}